-- Site-scoped test rows. Every site_id key cascades from qp_site, so deleting a site removes them; the tag's key to
-- its note includes the site, so a tag can only belong to a note of its own site.
create table it_note (
    id bigint generated by default as identity primary key,
    site_id bigint not null,
    text varchar(100) not null,
    constraint it_note_site_fk foreign key (site_id) references qp_site (id) on delete cascade,
    constraint it_note_site_id_uq unique (site_id, id)
);

create table it_note_tag (
    id bigint generated by default as identity primary key,
    site_id bigint not null,
    note_id bigint not null,
    label varchar(50) not null,
    constraint it_note_tag_site_fk foreign key (site_id) references qp_site (id) on delete cascade,
    constraint it_note_tag_note_fk foreign key (site_id, note_id) references it_note (site_id, id) on delete cascade
);
