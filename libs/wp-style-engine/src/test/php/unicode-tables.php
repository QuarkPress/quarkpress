 * Unicode-dependent classes in _wp_to_kebab_case's /u pattern, as PHP's bundled PCRE2 sees them: \d (decimal
 * digits) and \w (the word characters \b tests). Run it again only when the oracle's PCRE2 moves to a newer
 * Unicode version:
 *   php src/test/php/unicode-tables.php > src/main/java/org/quarkword/lib/wpstyleengine/UnicodeTables.java
 */
declare(strict_types=1);

function qw_ranges(string $pattern): array
{
    $ranges = [];
    $start = -1;
    for ($cp = 0; $cp <= 0x110000; $cp++) {
        $in = $cp <= 0x10FFFF && ($cp < 0xD800 || $cp > 0xDFFF) && preg_match($pattern, mb_chr($cp, 'UTF-8')) === 1;
        if ($in && $start < 0) {
            $start = $cp;
        } elseif (!$in && $start >= 0) {
            $ranges[] = [$start, $cp - 1];
            $start = -1;
        }
    }
    return $ranges;
}

function qw_table(string $name, string $doc, array $ranges): string
{
    $cells = [];
    foreach ($ranges as [$a, $b]) {
        $cells[] = sprintf('0x%X, 0x%X', $a, $b);
    }
    $out = "    /** $doc: " . count($ranges) . " ranges, each a first and last code point. */\n";
    $out .= "    static final int[] $name = {\n";
    foreach (array_chunk($cells, 4) as $row) {
        $out .= '        ' . implode(', ', $row) . ",\n";
    }
    return $out . "    };\n";
}

$pcre = explode(' ', PCRE_VERSION)[0];
echo <<<JAVA
package org.quarkword.lib.wpstyleengine;

/**
 * Fixed Unicode 17.0 character classes for {@link KebabCase}, so its output does not depend on the JDK's Unicode
 * version. They were generated by {@code src/test/php/unicode-tables.php} from the oracle php's PCRE2 $pcre, whose
 * Unicode data is 17.0, and are what WordPress's {@code /u} pattern uses: {@code \\d} and the word characters of
 * {@code \\b}. Do not edit by hand.
 */
final class UnicodeTables {

    private UnicodeTables() {}

    /** Whether {@code cp} lies in one of the sorted, disjoint {@code ranges}. */
    static boolean contains(int[] ranges, int cp) {
        int lo = 0;
        int hi = ranges.length / 2 - 1;
        while (lo <= hi) {
            int mid = (lo + hi) >>> 1;
            if (cp < ranges[2 * mid]) {
                hi = mid - 1;
            } else if (cp > ranges[2 * mid + 1]) {
                lo = mid + 1;
            } else {
                return true;
            }
        }
        return false;
    }


JAVA;
echo qw_table('DIGIT', 'PCRE2 {@code \\d} with UCP: the decimal digits (Nd)', qw_ranges('/\A\d\z/u'));
echo "\n";
echo qw_table('WORD', 'PCRE2 {@code \\w} with UCP: letters, numbers, non-spacing marks and connector punctuation', qw_ranges('/\A\w\z/u'));
echo "}\n";
