    /** True when the JDK's StAX parser accepts a code point as the first character of an element or target name. */
    static boolean isNameStart(int c) {
        int low = 0;
        int high = NAME_START.length / 2 - 1;
        while (low <= high) {
            int mid = (low + high) >>> 1;
            if (c < NAME_START[2 * mid]) {
                high = mid - 1;
            } else if (c > NAME_START[2 * mid + 1]) {
                low = mid + 1;
            } else {
                return true;
            }
        }
        return false;
    }
