package org.quarkpress.blocks;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.BooleanNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * The attributes a block type has as WordPress's block type registry answers them: the attributes the type declares,
 * in their order, then {@code lock} and {@code metadata} (objects) unless declared, then the attributes its supports
 * add, in the order WordPress's block supports add them, each only when the type has its support and the attribute is
 * not there yet: {@code align}; {@code className} (unless {@code supports.customClassName} is false); the colour
 * attributes {@code backgroundColor}, {@code textColor} and {@code gradient}; {@code fontSize} and {@code fontFamily}
 * (the experimental font family); {@code borderColor} (the experimental border's colour, or the whole experimental
 * border); {@code layout} (also from the experimental layout); {@code ariaLabel}; {@code anchor}. {@code style} is
 * added by the first support that wants it: colour, typography, the experimental border, then position, spacing,
 * dimensions, duotone or background (after {@code layout}), and last {@code customCSS} (on unless false), so
 * {@code customCSS: false} drops it only when no other support wants it. The supports {@code border}, {@code shadow}
 * and the rest of {@code filter} add none. A type whose supports turn {@code autoRegister} on also marks each declared
 * attribute of a simple type (string, number, integer or boolean) that has no {@code source} and whose {@code role}
 * is not {@code local} with {@code autoGenerateControl: true}.
 *
 * <p>What each support adds is data, read from {@code block-support-attributes.json} beside this class.
 */
public final class BlockSupports {

    private static final ObjectMapper JSON = new ObjectMapper();

    private static final String RESOURCE = "/org/quarkpress/blocks/block-support-attributes.json";

    private static final Set<String> SIMPLE_TYPES = Set.of("string", "number", "integer", "boolean");

    /**
     * A condition on the supports: a path, whether a missing last key counts as on, and whether a {@code true} earlier
     * key turns it on.
     */
    private record Condition(List<String> path, boolean onWhenMissing, boolean onWhenParentTrue) {}

    /** One attribute supports add: when any of its conditions holds, with its schema. */
    private record SupportAttribute(String name, List<Condition> anyOf, ObjectNode schema) {}

    private static final List<SupportAttribute> SUPPORT_ATTRIBUTES = read();

    private BlockSupports() {}

    /** The attributes of {@code type}, as described above; a new object on each call. */
    public static ObjectNode attributes(BlockType type) {
        ObjectNode attributes = type.declaredAttributes();
        ObjectNode supports = type.supports();
        if (on(supports.get("autoRegister"))) {
            markAutoGenerated(attributes);
        }
        for (String global : List.of("lock", "metadata")) {
            if (!attributes.has(global)) {
                attributes.putObject(global).put("type", "object");
            }
        }
        for (SupportAttribute added : SUPPORT_ATTRIBUTES) {
            if (!attributes.has(added.name()) && supported(supports, added)) {
                attributes.set(added.name(), added.schema().deepCopy());
            }
        }
        return attributes;
    }

    private static void markAutoGenerated(ObjectNode attributes) {
        for (Map.Entry<String, JsonNode> attribute : attributes.properties()) {
            if (!(attribute.getValue() instanceof ObjectNode definition)) {
                continue;
            }
            JsonNode type = definition.get("type");
            JsonNode role = definition.get("role");
            if (type != null
                    && type.isTextual()
                    && SIMPLE_TYPES.contains(type.textValue())
                    && !definition.has("source")
                    && !(role != null && role.isTextual() && role.textValue().equals("local"))) {
                definition.set("autoGenerateControl", BooleanNode.TRUE);
            }
        }
    }

    private static boolean supported(ObjectNode supports, SupportAttribute added) {
        for (Condition condition : added.anyOf()) {
            if (holds(supports, condition)) {
                return true;
            }
        }
        return false;
    }

    /**
     * Whether the condition holds: each key of its path before the last must be an object, or true (then the condition
     * holds only when it says so); the last key is on when true or an object or list, and when missing as the
     * condition says.
     */
    private static boolean holds(ObjectNode supports, Condition condition) {
        JsonNode node = supports;
        List<String> path = condition.path();
        for (int i = 0; i < path.size(); i++) {
            JsonNode value = node.get(path.get(i));
            boolean last = i == path.size() - 1;
            if (value == null || value.isMissingNode()) {
                return last && condition.onWhenMissing();
            }
            if (last) {
                return on(value);
            }
            if (value.isBoolean() && value.booleanValue()) {
                return condition.onWhenParentTrue();
            }
            if (!value.isObject()) {
                return false;
            }
            node = value;
        }
        return false;
    }

    /** A support is on when it is true, or an object or list (WordPress's test). */
    private static boolean on(JsonNode value) {
        return value != null && ((value.isBoolean() && value.booleanValue()) || value.isContainerNode());
    }

    private static List<SupportAttribute> read() {
        try (InputStream in = BlockSupports.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                throw new IllegalStateException("QuarkPress: " + RESOURCE + " is missing");
            }
            List<SupportAttribute> list = new ArrayList<>();
            for (JsonNode entry : JSON.readTree(in).get("attributes")) {
                List<Condition> anyOf = new ArrayList<>();
                for (JsonNode condition : entry.get("anyOf")) {
                    List<String> path = new ArrayList<>();
                    condition.get("path").forEach(key -> path.add(key.textValue()));
                    anyOf.add(new Condition(
                            List.copyOf(path),
                            condition.path("onWhenMissing").asBoolean(false),
                            condition.path("onWhenParentTrue").asBoolean(false)));
                }
                list.add(new SupportAttribute(
                        entry.get("name").textValue(), List.copyOf(anyOf), (ObjectNode) entry.get("schema")));
            }
            return List.copyOf(list);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
