-- Posts of every type, and the per-site lock that serializes post writes.
-- meta is json, not jsonb: json keeps the text as written, so object keys keep their order.
-- unique (site_id, id) is the composite parent key of the parent reference and of every site-scoped table that refers
-- to a post; the parent reference is composite so a post can only have a parent of its own site.
create table qw_post (
    id bigint generated by default as identity primary key,
    site_id bigint not null,
    type varchar(20) not null,
    status varchar(20) not null,
    slug varchar(200) not null default '',
    title text not null,
    content text not null,
    excerpt text not null,
    author_id bigint,
    parent_id bigint,
    menu_order int not null default 0,
    published_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    modified_at timestamp(6) with time zone not null,
    comment_status varchar(20) not null,
    ping_status varchar(20) not null,
    password varchar(255) not null default '',
    sticky boolean not null default false,
    guid varchar(255) not null,
    meta json not null default '{}',
    version int not null default 0,
    constraint qw_post_site_fk foreign key (site_id) references qw_site (id) on delete cascade,
    constraint qw_post_site_id_uq unique (site_id, id),
    constraint qw_post_author_fk foreign key (author_id) references qw_user_profile (id) on delete set null,
    constraint qw_post_parent_fk foreign key (site_id, parent_id) references qw_post (site_id, id) on delete cascade
);

create index qw_post_type_status_idx on qw_post (site_id, type, status, published_at, id);
create index qw_post_slug_idx on qw_post (site_id, slug);
create index qw_post_parent_idx on qw_post (site_id, parent_id);
create index qw_post_author_idx on qw_post (site_id, author_id);
create index qw_post_due_idx on qw_post (status, published_at);

create table qw_post_lock (
    site_id bigint primary key,
    constraint qw_post_lock_site_fk foreign key (site_id) references qw_site (id) on delete cascade
);
