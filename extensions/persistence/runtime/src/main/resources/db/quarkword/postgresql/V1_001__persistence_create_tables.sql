-- Option values are json, not jsonb: json keeps the text as written, so object keys keep their order.
create table qw_site (
    id bigint generated by default as identity primary key,
    domain varchar(200) not null,
    path varchar(100) not null,
    name varchar(255) not null,
    public_flag smallint not null default 1,
    archived boolean not null default false,
    mature boolean not null default false,
    spam boolean not null default false,
    deleted boolean not null default false,
    registered_at timestamp(6) with time zone not null default now(),
    updated_at timestamp(6) with time zone not null default now(),
    version integer not null default 0,
    constraint qw_site_domain_path_uq unique (domain, path)
);

create index qw_site_path_idx on qw_site (path);

create table qw_network_option (
    name varchar(191) primary key,
    value json not null,
    updated_at timestamp(6) with time zone not null default now()
);

create table qw_option (
    id bigint generated by default as identity primary key,
    site_id bigint not null,
    name varchar(191) not null,
    value json not null,
    autoload boolean not null default true,
    updated_at timestamp(6) with time zone not null default now(),
    constraint qw_option_site_fk foreign key (site_id) references qw_site (id) on delete cascade,
    constraint qw_option_site_name_uq unique (site_id, name)
);

create index qw_option_site_autoload_idx on qw_option (site_id, autoload);
