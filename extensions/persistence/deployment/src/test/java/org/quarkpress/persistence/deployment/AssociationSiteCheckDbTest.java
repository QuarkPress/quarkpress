package org.quarkpress.persistence.deployment;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import io.agroal.api.AgroalDataSource;
import io.quarkus.agroal.DataSource;
import io.quarkus.hibernate.orm.PersistenceUnit;
import io.quarkus.test.QuarkusExtensionTest;
import jakarta.inject.Inject;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EntityManager;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;
import org.hibernate.annotations.Filter;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.RegisterExtension;
import org.quarkpress.core.SiteId;
import org.quarkpress.persistence.SiteScope;
import org.quarkpress.persistence.runtime.SiteScopedEntity;
import org.quarkpress.scheduling.runtime.ScopeProbe;

class AssociationSiteCheckDbTest {

    @RegisterExtension
    static final QuarkusExtensionTest app = DbApp.with(
            AssociationSiteCheckDbTest.class,
            AssocParent.class,
            AssocChild.class,
            AssocProfile.class,
            AssocBase.class,
            AssocLeaf.class,
            ScopeProbe.class);

    @Entity
    @Table(name = "test_assoc_parent")
    @Filter(name = SiteScopedEntity.FILTER)
    public static class AssocParent extends SiteScopedEntity {
        @Id
        @GeneratedValue(strategy = GenerationType.IDENTITY)
        public Long id;

        @Column(nullable = false, length = 50)
        public String label;

        static AssocParent labelled(String label) {
            AssocParent parent = new AssocParent();
            parent.label = label;
            return parent;
        }
    }

    @Entity
    @Table(name = "test_assoc_child")
    @Filter(name = SiteScopedEntity.FILTER)
    public static class AssocChild extends SiteScopedEntity {
        @Id
        @GeneratedValue(strategy = GenerationType.IDENTITY)
        public Long id;

        @ManyToOne(optional = false)
        @JoinColumn(name = "parent_id", nullable = false)
        public AssocParent parent;

        static AssocChild of(AssocParent parent) {
            AssocChild child = new AssocChild();
            child.parent = parent;
            return child;
        }

        static AssocChild forSite(SiteId site, AssocParent parent) {
            AssocChild child = of(parent);
            child.assignSite(site);
            return child;
        }
    }

    @Entity
    @Table(name = "test_assoc_profile")
    @Filter(name = SiteScopedEntity.FILTER)
    public static class AssocProfile extends SiteScopedEntity {
        @Id
        @GeneratedValue(strategy = GenerationType.IDENTITY)
        public Long id;

        @OneToOne(optional = false)
        @JoinColumn(name = "parent_id", nullable = false)
        public AssocParent parent;
    }

    @MappedSuperclass
    public abstract static class AssocBase extends SiteScopedEntity {
        @ManyToOne(optional = false)
        @JoinColumn(name = "parent_id", nullable = false)
        public AssocParent parent;
    }

    @Entity
    @Table(name = "test_assoc_leaf")
    @Filter(name = SiteScopedEntity.FILTER)
    public static class AssocLeaf extends AssocBase {
        @Id
        @GeneratedValue(strategy = GenerationType.IDENTITY)
        public Long id;
    }

    @Inject
    @DataSource("quarkpress")
    AgroalDataSource dataSource;

    @Inject
    SiteScope scope;

    @Inject
    @PersistenceUnit("quarkpress")
    EntityManager em;

    @Inject
    TestSites sites;

    @Inject
    ScopeProbe probe;

    @BeforeEach
    void tables() {
        boolean mysql = TestDb.kind().equals("mysql");
        String id = mysql
                ? "id bigint not null auto_increment primary key"
                : "id bigint generated by default as identity primary key";
        Jdbc.update(
                dataSource,
                "create table if not exists test_assoc_parent (" + id + ", site_id bigint not null,"
                        + " label varchar(50) not null,"
                        + " constraint test_assoc_parent_site_fk foreign key (site_id) references qp_site (id) on delete cascade,"
                        + " constraint test_assoc_parent_site_id_uq unique (site_id, id))");
        Jdbc.update(
                dataSource,
                "create table if not exists test_assoc_child (" + id + ", site_id bigint not null,"
                        + " parent_id bigint not null,"
                        + " constraint test_assoc_child_site_fk foreign key (site_id) references qp_site (id) on delete cascade,"
                        + " constraint test_assoc_child_parent_fk foreign key (site_id, parent_id)"
                        + " references test_assoc_parent (site_id, id) on delete cascade)");

        Jdbc.update(
                dataSource,
                "create table if not exists test_assoc_profile (" + id + ", site_id bigint not null,"
                        + " parent_id bigint not null,"
                        + " constraint test_assoc_profile_site_fk foreign key (site_id) references qp_site (id) on delete cascade,"
                        + " constraint test_assoc_profile_parent_fk foreign key (site_id, parent_id)"
                        + " references test_assoc_parent (site_id, id) on delete cascade)");
        Jdbc.update(
                dataSource,
                "create table if not exists test_assoc_leaf (" + id + ", site_id bigint not null,"
                        + " parent_id bigint not null,"
                        + " constraint test_assoc_leaf_site_fk foreign key (site_id) references qp_site (id) on delete cascade,"
                        + " constraint test_assoc_leaf_parent_fk foreign key (site_id, parent_id)"
                        + " references test_assoc_parent (site_id, id) on delete cascade)");
    }

    private AssocParent parentOf(SiteId site) throws Exception {
        return scope.call(site, () -> {
            AssocParent parent = AssocParent.labelled("parent");
            em.persist(parent);
            em.flush();
            return parent;
        });
    }

    @Test
    void aRowOfTheSameSiteIsStored() throws Exception {
        SiteId a = sites.create("assoc-a");
        AssocParent parent = parentOf(a);
        Long childId = scope.call(a, () -> {
            AssocChild child = AssocChild.of(em.find(AssocParent.class, parent.id));
            em.persist(child);
            em.flush();
            return child.id;
        });
        assertThat(childId).isNotNull();
    }

    @Test
    void aLoadedRowOfAnotherSiteIsRefusedByTheListener() throws Exception {
        SiteId a = sites.create("assoc-a");
        SiteId b = sites.create("assoc-b");
        AssocParent parentOfA = parentOf(a);
        assertThatThrownBy(() -> scope.run(b, () -> {
                    em.persist(AssocChild.of(parentOfA));
                    em.flush();
                }))
                .isInstanceOf(IllegalStateException.class)
                .hasMessage("a row of site " + b.value() + " refers to a row of site " + a.value()
                        + " through AssocChild.parent");
    }

    @Test
    void anUpdateToAnotherSitesRowIsRefusedByTheListener() throws Exception {
        SiteId a = sites.create("assoc-a");
        SiteId b = sites.create("assoc-b");
        AssocParent parentOfA = parentOf(a);
        AssocParent parentOfB = parentOf(b);
        Long childId = scope.call(a, () -> {
            AssocChild child = AssocChild.of(em.find(AssocParent.class, parentOfA.id));
            em.persist(child);
            em.flush();
            return child.id;
        });
        assertThatThrownBy(() -> scope.run(a, () -> {
                    em.find(AssocChild.class, childId).parent = parentOfB;
                    em.flush();
                }))
                .isInstanceOf(IllegalStateException.class)
                .hasMessage("a row of site " + a.value() + " refers to a row of site " + b.value()
                        + " through AssocChild.parent");
    }

    @Test
    void aNetworkScopeInsertIsCheckedToo() throws Exception {
        SiteId a = sites.create("assoc-a");
        SiteId b = sites.create("assoc-b");
        AssocParent parentOfA = parentOf(a);
        assertThatThrownBy(() -> probe.inNetwork(() -> {
                    em.persist(AssocChild.forSite(b, em.find(AssocParent.class, parentOfA.id)));
                    em.flush();
                    return null;
                }))
                .isInstanceOf(IllegalStateException.class)
                .hasMessage("a row of site " + b.value() + " refers to a row of site " + a.value()
                        + " through AssocChild.parent");
    }

    @Test
    void anUninitializedReferenceIsLeftToTheCompositeKey() throws Exception {
        SiteId a = sites.create("assoc-a");
        SiteId b = sites.create("assoc-b");
        AssocParent parentOfA = parentOf(a);
        assertThatThrownBy(() -> scope.run(b, () -> {
                    em.persist(AssocChild.of(em.getReference(AssocParent.class, parentOfA.id)));
                    em.flush();
                }))
                .satisfies(failure -> assertThat(Failures.messages(failure)).contains("test_assoc_child_parent_fk"));
    }

    @Test
    void aOneToOneToAnotherSitesRowIsRefusedByTheListener() throws Exception {
        SiteId a = sites.create("assoc-a");
        SiteId b = sites.create("assoc-b");
        AssocParent parentOfA = parentOf(a);
        AssocProfile profile = new AssocProfile();
        profile.parent = parentOfA;
        assertThatThrownBy(() -> scope.run(b, () -> {
                    em.persist(profile);
                    em.flush();
                }))
                .isInstanceOf(IllegalStateException.class)
                .hasMessage("a row of site " + b.value() + " refers to a row of site " + a.value()
                        + " through AssocProfile.parent");
    }

    @Test
    void anAssociationInheritedFromAMappedSuperclassIsChecked() throws Exception {
        SiteId a = sites.create("assoc-a");
        SiteId b = sites.create("assoc-b");
        AssocParent parentOfA = parentOf(a);
        AssocLeaf leaf = new AssocLeaf();
        leaf.parent = parentOfA;
        assertThatThrownBy(() -> scope.run(b, () -> {
                    em.persist(leaf);
                    em.flush();
                }))
                .isInstanceOf(IllegalStateException.class)
                .hasMessage("a row of site " + b.value() + " refers to a row of site " + a.value()
                        + " through AssocBase.parent");
    }

    @Test
    void aNetworkScopeUpdateIsCheckedToo() throws Exception {
        SiteId a = sites.create("assoc-a");
        SiteId b = sites.create("assoc-b");
        AssocParent parentOfA = parentOf(a);
        AssocParent parentOfB = parentOf(b);
        Long childId = scope.call(a, () -> {
            AssocChild child = AssocChild.of(em.find(AssocParent.class, parentOfA.id));
            em.persist(child);
            em.flush();
            return child.id;
        });
        assertThatThrownBy(() -> probe.inNetwork(() -> {
                    AssocChild child = em.find(AssocChild.class, childId);
                    child.parent = em.find(AssocParent.class, parentOfB.id);
                    em.flush();
                    return null;
                }))
                .isInstanceOf(IllegalStateException.class)
                .hasMessage("a row of site " + a.value() + " refers to a row of site " + b.value()
                        + " through AssocChild.parent");
    }

    @Test
    void aRowThatPointsAcrossSitesCanStillBeDeleted() throws Exception {
        SiteId a = sites.create("assoc-a");
        SiteId b = sites.create("assoc-b");
        AssocParent parentOfA = parentOf(a);
        AssocParent parentOfB = parentOf(b);
        Long childId = scope.call(a, () -> {
            AssocChild child = AssocChild.of(em.find(AssocParent.class, parentOfA.id));
            em.persist(child);
            em.flush();
            return child.id;
        });
        scope.run(a, () -> {
            AssocChild child = em.find(AssocChild.class, childId);
            child.parent = parentOfB;
            em.remove(child);
            em.flush();
        });
        assertThat(scope.call(a, () -> em.find(AssocChild.class, childId))).isNull();
    }
}
